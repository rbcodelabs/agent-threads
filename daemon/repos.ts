/**
 * Repositories the daemon keeps cloned under its workspace root (`<dataDir>/workspace/<name>` by default), so a
 * session can work on code without anyone logging in to the machine first.
 *
 * Authentication. A private repository needs a token. It is pushed with `creds.push` (kind `github`, field `GH_TOKEN`;
 * `GITHUB_TOKEN` also works) and is handed to git ONLY through the environment of the git child process, answered by
 * a generated `GIT_ASKPASS` script. It is never in argv, in a clone URL, in `.git/config`, or in a reply: URLs with
 * embedded credentials are refused, and every message that leaves this module is scrubbed of the token.
 *
 * The script answers only for the hosts of the configured repositories (and github.com): a remote that redirects to,
 * or a submodule that points at, some other host gets no token.
 *
 * The same token reaches the agent's own process as `GH_TOKEN` (for `gh`) plus the same askpass wiring (for `git
 * push`) through `sessionEnv()`; nothing else in the daemon sees it.
 */
import { execFile } from 'node:child_process';
import { existsSync, readFileSync, readdirSync, renameSync, rmSync, statSync, chmodSync } from 'node:fs';
import { isAbsolute, join, relative, resolve, sep } from 'node:path';
import { randomBytes } from 'node:crypto';
import { MAX_REPOS, validateRepoSpecs, type RepoSpec, type RepoState, type RepoStatus, type ReposReply } from '../src/protocol';
import type { CredStore } from './credStore';
import { ensureDir, writeFileAtomic } from './fsutil';

export class RepoError extends Error {}

/** Where the token is looked up: `github.GH_TOKEN`, else any kind with `GH_TOKEN`, else `GITHUB_TOKEN`. */
const TOKEN_LOOKUPS = ['github.GH_TOKEN', 'GH_TOKEN', 'github.GITHUB_TOKEN', 'GITHUB_TOKEN'];
export const GIT_PASSWORD_ENV = 'AGENT_THREADS_GIT_PASSWORD';
const GIT_TIMEOUT_MS = 10 * 60_000;
const HOST = /^[A-Za-z0-9]([A-Za-z0-9.-]*[A-Za-z0-9])?$/;
const SCP_LIKE = /^([A-Za-z0-9._-]+)@([A-Za-z0-9.-]+):[^\s:][^\s]*$/;
const AUTH_ERROR = /authentication failed|could not read (username|password)|terminal prompts disabled|invalid username or password|permission denied \(publickey\)|returned error: 40[13]|requested url returned error: 40[13]|repository not found|http 40[13]/i;

export interface GitResult { stdout: string; stderr: string }
/** Runs git with `args` in `cwd` (optional) and `env`; rejects with an Error whose message is git's stderr. */
export type GitRunner = (args: string[], opts: { cwd?: string; env: NodeJS.ProcessEnv; timeoutMs?: number }) => Promise<GitResult>;

export const realGit: GitRunner = (args, opts) => new Promise((resolvePromise, reject) => {
  execFile('git', args, { cwd: opts.cwd, env: opts.env, timeout: opts.timeoutMs ?? GIT_TIMEOUT_MS, maxBuffer: 16 * 1024 * 1024, windowsHide: true }, (err, stdout, stderr) => {
    if (err) {
      const e = new Error(String(stderr || err.message).trim() || 'git failed');
      reject(e);
      return;
    }
    resolvePromise({ stdout: String(stdout), stderr: String(stderr) });
  });
});

/** Why this clone URL is not acceptable, or null. Credentials in a URL, `ext::` and other transports are refused. */
export function repoUrlProblem(url: string, allowLocal: boolean): string | null {
  if (SCP_LIKE.test(url)) return null;
  if (url.startsWith('/') || url.startsWith('file://')) {
    return allowLocal ? null : 'local paths are not allowed (set allowLocalRepoUrls in config.json to clone from this machine\'s disk)';
  }
  let u: URL;
  try { u = new URL(url); } catch { return 'url is not a valid clone URL (use https://host/owner/repo.git)'; }
  if (u.protocol !== 'https:' && u.protocol !== 'ssh:') return 'url must start with https:// or ssh://';
  if (u.password || (u.protocol === 'https:' && u.username)) return 'url must not contain credentials; push a token with `agent-threads creds push` instead';
  if (!HOST.test(u.hostname)) return 'url has no valid host';
  return null;
}

/** Host of an https/ssh/scp-like URL, lower-cased; undefined for local paths. */
export function repoHost(url: string): string | undefined {
  const scp = SCP_LIKE.exec(url);
  if (scp) return scp[2].toLowerCase();
  try {
    const u = new URL(url);
    return u.protocol === 'file:' ? undefined : u.hostname.toLowerCase() || undefined;
  } catch { return undefined; }
}

/** The `GIT_ASKPASS` script: answers only for `hosts`, from the environment. Pure, so a test can inspect it. */
export function askpassScript(hosts: readonly string[]): string {
  const safe = hosts.filter((h) => HOST.test(h));
  const patterns = safe.flatMap((h) => [`*//${h}\\'*`, `*@${h}\\'*`, `*//${h}/*`, `*@${h}/*`]).join('|');
  return [
    '#!/bin/sh',
    '# Generated by agent-threads. Answers git\'s credential prompts for the configured hosts from the environment.',
    `case "$1" in ${patterns || '__none__'}) ;; *) exit 1 ;; esac`,
    'case "$1" in',
    '  Username*) printf \'%s\\n\' x-access-token ;;',
    `  *) printf '%s\\n' "$${GIT_PASSWORD_ENV}" ;;`,
    'esac',
    '',
  ].join('\n');
}

interface RepoRecord {
  syncedAt?: number;
  error?: string;
  auth?: boolean;
}

export interface ReposManagerOptions {
  dataDir: string;
  /** Absolute directory the clones live under. */
  root: string;
  creds: CredStore;
  getRepos(): RepoSpec[];
  /** Persist a new list (config.json). */
  setRepos(repos: RepoSpec[]): void;
  allowLocalUrls?: boolean;
  now?: () => number;
  git?: GitRunner;
  env?: NodeJS.ProcessEnv;
  log?: (line: string) => void;
  /** Older than this since the last good fetch = `stale` (default 24 h). */
  staleAfterMs?: number;
  /** A session starting inside a repo refetches it only if the last fetch is older than this (default 5 min). */
  refreshMinGapMs?: number;
}

export class ReposManager {
  readonly root: string;
  private readonly now: () => number;
  private readonly git: GitRunner;
  private readonly stateFile: string;
  private readonly askpassFile: string;
  private records: Record<string, RepoRecord> = {};
  /** Repositories with a sync queued or running (a count, because the same one can be queued twice). */
  private readonly syncing = new Map<string, number>();
  private chain: Promise<void> = Promise.resolve();

  constructor(private readonly opts: ReposManagerOptions) {
    this.root = opts.root;
    this.now = opts.now ?? (() => Date.now());
    this.git = opts.git ?? realGit;
    this.stateFile = join(opts.dataDir, 'repos-state.json');
    this.askpassFile = join(opts.dataDir, 'repos', 'askpass.sh');
    try {
      const parsed: unknown = JSON.parse(readFileSync(this.stateFile, 'utf8'));
      if (typeof parsed === 'object' && parsed !== null) this.records = parsed as Record<string, RepoRecord>;
    } catch { /* first run */ }
  }

  // ── status ───────────────────────────────────────────────────────────────

  status(): ReposReply {
    return { root: this.root, repos: this.opts.getRepos().map((spec) => this.statusOf(spec)) };
  }

  private dirOf(name: string): string { return join(this.root, name); }
  private isCloned(name: string): boolean { return existsSync(join(this.dirOf(name), '.git')); }

  private statusOf(spec: RepoSpec): RepoStatus {
    const rec = this.records[spec.name] ?? {};
    const cloned = this.isCloned(spec.name);
    const stale = rec.syncedAt === undefined || this.now() - rec.syncedAt > (this.opts.staleAfterMs ?? 24 * 3_600_000);
    let state: RepoState;
    if (this.syncing.has(spec.name)) state = 'syncing';
    else if (rec.error) state = rec.auth ? 'auth_failed' : cloned ? 'stale' : 'error';
    else if (!cloned) state = 'not_cloned';
    else state = stale ? 'stale' : 'cloned';
    return {
      ...spec,
      state,
      path: this.dirOf(spec.name),
      ...(rec.syncedAt !== undefined ? { syncedAt: rec.syncedAt } : {}),
      ...(rec.error ? { error: rec.error } : {}),
    };
  }

  // ── commands ─────────────────────────────────────────────────────────────

  /** `repos.sync`: optionally replace the list, then bring every repository up to date. */
  async sync(repos?: unknown, wait = false): Promise<ReposReply> {
    if (repos !== undefined) {
      const problem = validateRepoSpecs(repos);
      if (problem) throw new RepoError(problem);
      const next = (repos as RepoSpec[]).map((r) => ({ name: r.name, url: r.url, ...(r.branch ? { branch: r.branch } : {}) }));
      for (const r of next) {
        const urlProblem = repoUrlProblem(r.url, this.opts.allowLocalUrls === true);
        if (urlProblem) throw new RepoError(`${r.name}: ${urlProblem}`);
      }
      this.opts.setRepos(next);
      // A repository dropped from the list keeps its clone on disk (it may hold unpushed work) but loses its record.
      const keep = new Set(next.map((r) => r.name));
      this.records = Object.fromEntries(Object.entries(this.records).filter(([name]) => keep.has(name)));
      this.saveRecords();
    }
    const pending = this.opts.getRepos().map((r) => this.enqueue(r));
    if (wait) await Promise.all(pending);
    return this.status();
  }

  /** Bring every configured repository up to date in the background (daemon start). */
  syncAll(): Promise<void> {
    return Promise.all(this.opts.getRepos().map((r) => this.enqueue(r))).then(() => undefined);
  }

  /**
   * A session is starting in `cwd`: if that is inside a configured clone whose last fetch is old, refresh it in the
   * background. Never blocks or fails the session.
   */
  refreshForCwd(cwd: string): void {
    const rel = relative(this.root, resolve(cwd));
    if (rel === '' || rel.startsWith('..') || isAbsolute(rel)) return;
    const name = rel.split(sep)[0];
    const spec = this.opts.getRepos().find((r) => r.name === name);
    if (!spec || this.syncing.has(name)) return;
    const syncedAt = this.records[name]?.syncedAt;
    if (syncedAt !== undefined && this.now() - syncedAt < (this.opts.refreshMinGapMs ?? 5 * 60_000)) return;
    void this.enqueue(spec);
  }

  /**
   * Environment additions for the agent's own process: `GH_TOKEN` for `gh`, and askpass wiring so `git push` over https
   * authenticates. Empty when no token is stored.
   */
  sessionEnv(): Record<string, string> {
    const token = this.token();
    if (!token) return {};
    return { GH_TOKEN: token, ...this.gitAuthEnv(token) };
  }

  // ── internals ────────────────────────────────────────────────────────────

  private token(): string | undefined {
    for (const key of TOKEN_LOOKUPS) {
      const v = this.opts.creds.lookup(key);
      if (v) return v;
    }
    return undefined;
  }

  private gitAuthEnv(token: string): Record<string, string> {
    const hosts = [...new Set(['github.com', ...this.opts.getRepos().map((r) => repoHost(r.url)).filter((h): h is string => !!h)])];
    writeFileAtomic(this.askpassFile, askpassScript(hosts));
    chmodSync(this.askpassFile, 0o700);
    return { GIT_ASKPASS: this.askpassFile, [GIT_PASSWORD_ENV]: token, GIT_TERMINAL_PROMPT: '0' };
  }

  private gitEnv(token: string | undefined): NodeJS.ProcessEnv {
    const base = this.opts.env ?? process.env;
    const env: NodeJS.ProcessEnv = {
      PATH: base.PATH, HOME: base.HOME, LANG: 'C', LC_ALL: 'C',
      GIT_TERMINAL_PROMPT: '0', GIT_CONFIG_NOSYSTEM: '1',
      GIT_ALLOW_PROTOCOL: this.opts.allowLocalUrls ? 'https:ssh:file' : 'https:ssh',
    };
    if (token) Object.assign(env, this.gitAuthEnv(token));
    return env;
  }

  private enqueue(spec: RepoSpec): Promise<void> {
    this.syncing.set(spec.name, (this.syncing.get(spec.name) ?? 0) + 1);
    const run = this.chain.then(() => this.syncOne(spec));
    this.chain = run.catch(() => undefined);
    return run.catch(() => undefined);
  }

  private scrub(text: string, token: string | undefined): string {
    let out = text;
    if (token) out = out.split(token).join('***');
    // Userinfo in a URL a git message echoes.
    out = out.replace(/(https?|ssh):\/\/[^/\s@]+@/gi, '$1://');
    return out.replace(/\s+/g, ' ').trim().slice(0, 300);
  }

  private async syncOne(spec: RepoSpec): Promise<void> {
    const name = spec.name;
    const token = this.token();
    try {
      const urlProblem = repoUrlProblem(spec.url, this.opts.allowLocalUrls === true);
      if (urlProblem) throw new RepoError(urlProblem);
      const env = this.gitEnv(token);
      const dir = this.dirOf(name);
      const noHelper = ['-c', 'credential.helper='];
      if (!this.isCloned(name)) {
        ensureDir(this.root);
        if (existsSync(dir) && readdirSync(dir).length > 0) throw new RepoError(`${dir} exists and is not a git repository`);
        const tmp = join(this.root, `.clone-${name}-${randomBytes(4).toString('hex')}`);
        try {
          await this.git([...noHelper, 'clone', ...(spec.branch ? ['--branch', spec.branch] : []), '--', spec.url, tmp], { env });
          if (existsSync(dir)) rmSync(dir, { recursive: true, force: true });
          renameSync(tmp, dir);
        } finally {
          rmSync(tmp, { recursive: true, force: true });
        }
      } else {
        const origin = (await this.git(['-C', dir, 'remote', 'get-url', 'origin'], { env }).catch(() => ({ stdout: '' }))).stdout.trim();
        if (origin !== spec.url) await this.git(['-C', dir, 'remote', 'set-url', 'origin', spec.url], { env });
        await this.git([...noHelper, '-C', dir, 'fetch', '--prune', 'origin'], { env });
        await this.fastForward(dir, spec.branch, env);
      }
      this.records[name] = { syncedAt: this.now() };
      this.opts.log?.(`repo ${name}: up to date`);
    } catch (err) {
      const raw = err instanceof Error ? err.message : String(err);
      const auth = AUTH_ERROR.test(raw);
      const hint = auth && !token ? ' (no token is stored: push one with `agent-threads creds push github GH_TOKEN`)' : '';
      this.records[name] = { ...(this.records[name]?.syncedAt !== undefined ? { syncedAt: this.records[name].syncedAt } : {}), error: this.scrub(raw, token) + hint, auth };
      this.opts.log?.(`repo ${name}: ${auth ? 'authentication failed' : 'sync failed'}: ${this.records[name].error}`);
    } finally {
      const left = (this.syncing.get(name) ?? 1) - 1;
      if (left > 0) this.syncing.set(name, left); else this.syncing.delete(name);
      this.saveRecords();
    }
  }

  /** Move a clean checkout of the tracked branch forward so a new worktree starts from current code. Best effort. */
  private async fastForward(dir: string, branch: string | undefined, env: NodeJS.ProcessEnv): Promise<void> {
    try {
      const current = (await this.git(['-C', dir, 'symbolic-ref', '--short', 'HEAD'], { env })).stdout.trim();
      if (!current || (branch && current !== branch)) return;
      if ((await this.git(['-C', dir, 'status', '--porcelain'], { env })).stdout.trim()) return;
      await this.git(['-C', dir, 'merge', '--ff-only', `origin/${current}`], { env });
    } catch { /* diverged, detached or no upstream: leave the checkout alone */ }
  }

  private saveRecords(): void {
    try { writeFileAtomic(this.stateFile, `${JSON.stringify(this.records)}\n`); } catch (err) { this.opts.log?.(`repo state not saved: ${String(err)}`); }
  }
}

/** The configured clone count must stay sane even if a config file was edited by hand. */
export function sanitizeConfiguredRepos(raw: unknown): RepoSpec[] {
  if (raw === undefined) return [];
  const problem = validateRepoSpecs(raw);
  if (problem) throw new Error(`invalid repos: ${problem}`);
  return (raw as RepoSpec[]).slice(0, MAX_REPOS).map((r) => ({ name: r.name, url: r.url, ...(r.branch ? { branch: r.branch } : {}) }));
}

/** Is `p` a directory (used by the pruner and the tests)? */
export function isDir(p: string): boolean {
  try { return statSync(p).isDirectory(); } catch { return false; }
}
