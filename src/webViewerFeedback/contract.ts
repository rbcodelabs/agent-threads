/**
 * Web Viewer element feedback contract, version 1 (ADR 0056).
 *
 * Types and constants only: zero runtime dependencies and zero imports so
 * `agent-threads` vendors a byte-for-byte identical copy. Everything crossing
 * this boundary is plain data (plus the handler object registered by the plugin
 * and the `AbortSignal` passed by Geode).
 *
 * Trust model:
 * - Origin E (embedder-verified): `page.url`, `page.origin`, `selectionId`,
 *   `viewSessionId`, `viewportPreset`, `capturedAt`, `submittedAt`, `stale`,
 *   and screenshot PNG container metadata.
 * - Origin U (embedder UI user input): `comment`, `threadId`.
 * - Origin G (untrusted guest page DOM): `page.title` and every DOM-derived
 *   field on `WebViewerElementSelection`. Render via `textContent` only and
 *   keep strictly inside an untrusted data fence when constructing prompts.
 */

/** Contract versions supported by this host/plugin build. */
export const WEB_VIEWER_FEEDBACK_CONTRACT_VERSIONS = [1] as const;

/** Maximum time allowed for `handler.submit(...)` before Geode aborts. */
export const WEB_VIEWER_FEEDBACK_SUBMIT_TIMEOUT_MS = 15_000;

/** Maximum time allowed for `handler.listThreads(...)` before Geode aborts. */
export const WEB_VIEWER_FEEDBACK_THREADS_TIMEOUT_MS = 5_000;

/** Sentinel `threadId` requesting creation of a new thread for the pick. */
export const WEB_VIEWER_NEW_THREAD_ID = "__new__";

/** Geode-derived from the registering plugin manifest (`id`, `name`). */
export interface WebViewerFeedbackOwner {
  readonly pluginId: string;
  readonly displayName: string;
}

/** Host-verified (Origin E) committed main-frame HTTP(S) page identity. */
export interface WebViewerPageTarget {
  /** Committed `http:` or `https:` URL verified by Geode (`<= 2048` UTF-16 units). */
  readonly url: string;
  /** RFC 6454 serialized origin (`scheme://host[:port]`) derived from `url`. */
  readonly origin: string;
  /** Cleaned plain-text page title (`<= 500` UTF-16 units; treat as Origin G). */
  readonly title: string;
}

/** Candidate destination thread displayed in the PickPopover switcher. */
export interface WebViewerThreadOption {
  /** Non-empty thread ID (`1..256` UTF-16 units; never `"__new__"`). */
  readonly id: string;
  /** Cleaned plain-text thread title (`1..160` UTF-16 units). */
  readonly title: string;
  /** Optional plain-text project or workspace label (`<= 120` UTF-16 units). */
  readonly subtitle?: string;
  readonly active: boolean;
  readonly busy: boolean;
  readonly planMode: boolean;
}

export interface WebViewerThreadList {
  /** At most 50 open threads, ordered active-first then most-recently-updated. */
  readonly threads: readonly WebViewerThreadOption[];
  readonly allowNewThread: boolean;
}

export interface WebViewerRect {
  readonly x: number;
  readonly y: number;
  readonly width: number;
  readonly height: number;
}

export type WebViewerViewportPreset = "desktop" | "tablet" | "mobile" | "custom" | "fill";

export type WebViewerScreenshotOmittedReason = "too-large" | "capture-failed" | "empty-rect";

export interface WebViewerElementScreenshot {
  readonly mimeType: "image/png";
  /** `1..524288` bytes, PNG signature and IHDR dimensions verified. */
  readonly bytes: Uint8Array;
  /** Pixel width of the PNG image. */
  readonly width: number;
  /** Pixel height of the PNG image. */
  readonly height: number;
  /** Crop rectangle in guest viewport CSS px (element + 8 px padding, clipped). */
  readonly cssRect: WebViewerRect;
  readonly devicePixelRatio: number;
  readonly downscaled: boolean;
}

export interface WebViewerElementSelection {
  readonly schemaVersion: 1;
  // ---- Origin E: produced by Geode's embedder (trusted) ----
  /** `/^sel_[0-9a-f]{32}$/`, 128 random bits generated by Geode. */
  readonly selectionId: string;
  /** Per-WebView-instance session identifier generated by Geode. */
  readonly viewSessionId: string;
  readonly viewportPreset: WebViewerViewportPreset;
  /** ISO 8601 UTC timestamp from Geode's clock. */
  readonly capturedAt: string;
  // ---- Origin G: extracted from guest page DOM (UNTRUSTED data) ----
  /** `location.pathname + location.search + location.hash` (or pathname + hash), `<= 512`. */
  readonly route: string;
  /** Lower-case local tag name, `/^[a-z][a-z0-9:-]{0,31}$/`. */
  readonly tag: string;
  /** Verified CSS selector (`<= 512`). */
  readonly selector: string;
  /** Up to 3 distinct alternate selectors, each `<= 512`. */
  readonly selectorAlternates: readonly string[];
  /** Normalized visible text anchor (`<= 80`). */
  readonly textAnchor: { readonly tag: string; readonly text: string };
  /** Nearest heading text or landmark label (`<= 120`), or `null`. */
  readonly landmark: string | null;
  /** Sanitized outerHTML snippet (`<= 4096` UTF-16 units including truncation marker). */
  readonly outerHTML: { readonly html: string; readonly truncated: boolean };
  /** Up to 3 ancestor summaries (`id <= 128`, up to 8 `classes` each `<= 64`). */
  readonly ancestors: readonly {
    readonly tag: string;
    readonly id: string | null;
    readonly classes: readonly string[];
  }[];
  /** Keys restricted to the 40-property inspector style allowlist; values `<= 200`. */
  readonly computedStyles: Readonly<Record<string, string>>;
  /** CSS px bounds; `document` = `viewport` + scroll offset. */
  readonly boundingBox: {
    readonly viewport: WebViewerRect;
    readonly document: WebViewerRect;
  };
  readonly viewport: {
    readonly width: number;
    readonly height: number;
    readonly devicePixelRatio: number;
    readonly scrollX: number;
    readonly scrollY: number;
  };
  /** `role <= 64`, `name <= 200`, `tabIndex` integer in `[-1, 32767]`. */
  readonly a11y: {
    readonly role: string | null;
    readonly name: string | null;
    readonly tabIndex: number | null;
  };
}

export interface WebViewerFeedbackRequest {
  readonly contractVersion: 1;
  readonly page: WebViewerPageTarget;
  /** Selected thread ID from `listThreads`, or `WEB_VIEWER_NEW_THREAD_ID` (`"__new__"`). */
  readonly threadId: string;
  /** Trimmed user comment typed in Geode's popover (`1..4000` UTF-16 units). */
  readonly comment: string;
  /** Validated element selection; Origin-G fields inside are untrusted page data. */
  readonly selection: WebViewerElementSelection;
  readonly screenshot: WebViewerElementScreenshot | null;
  /** Non-null iff `screenshot` is `null`. */
  readonly screenshotOmitted: WebViewerScreenshotOmittedReason | null;
  /** True when in-page navigation or layout mutation occurred between pick and send. */
  readonly stale: boolean;
  /** ISO 8601 UTC timestamp. */
  readonly submittedAt: string;
}

export type WebViewerFeedbackRejectReason =
  | "busy"
  | "invalid"
  | "unsupported"
  | "unavailable"
  | "failed";

export type WebViewerFeedbackDelivery = "sent" | "queued";

export type WebViewerFeedbackResult =
  | {
      readonly status: "accepted";
      readonly delivery: WebViewerFeedbackDelivery;
      readonly threadId: string;
      readonly message?: string;
    }
  | {
      readonly status: "rejected";
      readonly reason: WebViewerFeedbackRejectReason;
      readonly message: string;
    };

export type WebViewerFeedbackRegistration =
  | { readonly status: "registered"; dispose(): void }
  | {
      readonly status: "unsupported-version" | "conflict" | "invalid" | "unavailable";
      readonly message: string;
      /** Idempotent no-op when registration did not succeed. */
      dispose(): void;
    };

/** Read-only registry facade exposed at `app.webViewerFeedback`. */
export interface WebViewerFeedbackRegistry {
  readonly contractVersions: readonly number[];
  /** True when an active handler accepts `target`. */
  has(target: WebViewerPageTarget): boolean;
  /** Subscribes to handler registration changes; returns unsubscribe function. */
  onDidChange(listener: () => void): () => void;
}

export interface WebViewerFeedbackHandler {
  /** Must match a version in `app.webViewerFeedback.contractVersions`. */
  readonly contractVersion: 1;
  /**
   * Optional synchronous filter. Throwing or returning a non-boolean counts as `false`.
   * Omitted means "handles every HTTP(S) Web Viewer page target".
   */
  canHandle?(target: WebViewerPageTarget): boolean;
  /**
   * Returns candidate destination threads for the Pick popover thread switcher.
   */
  listThreads(
    target: WebViewerPageTarget,
    context: { readonly signal: AbortSignal },
  ): Promise<WebViewerThreadList>;
  /**
   * Delivers or queues the picked element feedback into `request.threadId` (or a new thread).
   * Must be idempotent per `request.selection.selectionId`.
   */
  submit(
    request: WebViewerFeedbackRequest,
    context: { readonly signal: AbortSignal },
  ): Promise<WebViewerFeedbackResult>;
}
