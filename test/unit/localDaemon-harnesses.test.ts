const PLUGIN = '0.65.0';
const running: Observed = {
  supported: true, runtimeInstalled: true, runtimeRunning: true, imageReady: true, volumesPresent: true, container: 'running',
  containerVersion: PLUGIN, containerSpec: 'old', health: 'ok', welcome: { daemonVersion: PLUGIN, protocol: 1, minClientVersion: '0.0.0' },
  tokenInKeychain: true, tokenAccepted: 'yes', credentialInKeychain: false, credentialInVolume: false, registered: true,
};
const desired = (over: Partial<Desired> = {}): Desired => ({ enabled: true, pluginVersion: PLUGIN, specSignature: 'new', ...over });

describe('assess with harness toggles', () => {
  it('a changed signature on a stopped container recreates it, rebuilding the layer when the new image is missing', () => {
    const stopped: Observed = { ...running, container: 'stopped', health: 'na', harnesses: ['claude', 'codex'], imageReady: false };
    expect(assess(stopped, desired()).plan).toEqual(['remove-container', 'pull-image', 'build-image', 'prepare-volumes', 'create-container']);
    expect(assess({ ...stopped, imageReady: true }, desired()).plan).toEqual(['remove-container', 'prepare-volumes', 'create-container']);
  });

  it('a running container with a changed signature reports drift (Apply changes), without restarting anything by itself', () => {
    const a = assess({ ...running, harnesses: ['claude', 'codex'], credentialInKeychain: true, credentialInVolume: true }, desired());
    expect(a.drift).toBe(true);
    expect(a.status).toBe('running');
    expect(a.plan).toEqual([]);
  });

  it('the version rule is unchanged by toggles: an incompatible stopped daemon is still rebuilt at the plugin version', () => {
    const a = assess({ ...running, container: 'stopped', health: 'na', welcome: undefined, containerVersion: '0.60.0', containerSpec: 'new', credentialInKeychain: true, credentialInVolume: true }, desired());
    expect(a.update).toBe('required');
    expect(a.plan[0]).toBe('remove-container');
  });

  it('Claude off: no Claude sign-in is asked for, and a stray keychain token is not applied', () => {
    expect(assess({ ...running, harnesses: ['codex'] }, desired({ specSignature: 'old' }))).toMatchObject({ status: 'running', needsSignIn: false });
    expect(assess({ ...running, harnesses: ['codex'], credentialInKeychain: true }, desired({ specSignature: 'old' })).plan).toEqual([]);
    // Claude on keeps the old behaviour
    expect(assess({ ...running, harnesses: ['claude', 'codex'] }, desired({ specSignature: 'old' }))).toMatchObject({ status: 'needs-sign-in', needsSignIn: true });
    expect(assess(running, desired({ specSignature: 'old' })).status).toBe('needs-sign-in');
  });
});

