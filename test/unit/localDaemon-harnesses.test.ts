const CLAUDE = 'sk-ant-oat01-TESTTOKEN';
const imageOf = (h: ReturnType<typeof makeHarness>, set?: string[]) => h.readState().images[localImageRef(h.pluginVersion, set)];

describe('controller: toggles drive the image and the daemon', () => {
  it('Set up with all three builds that image, installs the CLIs by build arg, and starts the daemon with that allowed set', async () => {
    const h = makeHarness({ settings: { enabled: false, port: 7433, harnesses: ['claude', 'codex', 'opencode'] }, secrets: { [CONTAINER_AUTH_TOKEN_SECRET]: CLAUDE } });
    const a = await h.controller.setUp();
    expect(a.status).toBe('running');
    const built = imageOf(h, ['claude', 'codex', 'opencode']);
    expect(built).toMatchObject({ built: true, harnesses: ['claude', 'codex', 'opencode'] });
    expect(h.readState().images[localImageRef(h.pluginVersion)]).toBeUndefined();
    const build = h.calls().find((c) => c.startsWith('build'))!;
    expect(build).toContain('INSTALL_CODEX=1');
    expect(build).toContain('INSTALL_OPENCODE=1');
    const container = Object.values(h.readState().containers)[0]!;
    expect(container.env).toContain('AGENT_THREADS_HARNESSES=claude,codex,opencode');
    // a verify ran for every CLI in the set
    expect(h.calls().some((c) => c.includes('command -v codex') && c.includes('command -v opencode'))).toBe(true);
  });

  it('Claude off: Set up needs no Claude sign-in, builds no Claude layer, and ensureRunning does not demand one', async () => {
    const h = makeHarness({ settings: { enabled: false, port: 7433, harnesses: ['codex'] } });
    const a = await h.controller.setUp();
    expect(a).toMatchObject({ status: 'running', needsSignIn: false });
    expect(imageOf(h, ['codex'])?.harnesses).toEqual(['codex']);
    expect(Object.values(h.readState().containers)[0]!.env).toContain('AGENT_THREADS_HARNESSES=codex');
    await expect(h.controller.ensureRunning()).resolves.toBeUndefined();
    await expect(h.controller.signIn({ onProgress: vi.fn(), onUrl: vi.fn(), onCodePrompt: async () => null })).resolves.toMatchObject({ ok: false, error: expect.stringContaining('Claude is turned off') });
  });

  it('changing a toggle changes the signature: the running daemon shows drift, Apply changes (update) rebuilds the layer and replaces the container', async () => {
    const h = makeHarness({ secrets: { [CONTAINER_AUTH_TOKEN_SECRET]: CLAUDE } });
    await h.controller.setUp();
    expect((await h.controller.snapshot()).assessment.drift).toBe(false);
    expect(await h.controller.setHarnesses(['claude', 'codex'])).toEqual(['claude', 'codex']);
    expect(h.settings?.harnesses).toEqual(['claude', 'codex']);
    const before = await h.controller.snapshot();
    expect(before.assessment.drift).toBe(true);
    expect(before.observed.imageReady).toBe(false);
    expect(before.harnesses).toEqual(['claude', 'codex']);
    await h.controller.update();
    expect(imageOf(h, ['claude', 'codex'])).toMatchObject({ built: true, harnesses: ['claude', 'codex'] });
    const after = await h.controller.snapshot();
    expect(after.assessment.drift).toBe(false);
    expect(after.assessment.status).toBe('running');
    expect(Object.values(h.readState().containers)[0]!.env).toContain('AGENT_THREADS_HARNESSES=claude,codex');
    // data and token survive the replacement
    expect(h.readState().volumes[dataVolumeFor(h.vaultPath)]?.tokens?.some((t) => t.revokedAt === null)).toBe(true);
  });

  it('a stopped daemon picks up a toggle on Start (plan: replace the container, rebuild the layer)', async () => {
    const h = makeHarness({ secrets: { [CONTAINER_AUTH_TOKEN_SECRET]: CLAUDE } });
    await h.controller.setUp();
    await h.controller.stop();
    await h.controller.setHarnesses(['claude', 'opencode']);
    const planned = (await h.controller.snapshot()).assessment.plan;
    expect(planned).toEqual(expect.arrayContaining(['remove-container', 'build-image', 'create-container']));
    await h.controller.start();
    expect(imageOf(h, ['claude', 'opencode'])?.harnesses).toEqual(['claude', 'opencode']);
    expect(Object.values(h.readState().containers)[0]!.env).toContain('AGENT_THREADS_HARNESSES=claude,opencode');
  });

  it('never stores an empty set, and refuses to change it while an operation runs', async () => {
    const h = makeHarness();
    expect(await h.controller.setHarnesses([])).toEqual(['claude']);
    expect(await h.controller.setHarnesses(['bogus', 'codex'])).toEqual(['codex']);
    const op = h.controller.setUp();
    await expect(h.controller.setHarnesses(['claude'])).rejects.toMatchObject({ code: 'busy' });
    await op;
  });

  it('a failed build leaves the daemon alone and names the CLIs it was adding', async () => {
    const h = makeHarness({ settings: { enabled: false, port: 7433, harnesses: ['claude', 'codex'] }, fail: ['build'] });
    const err = await h.controller.setUp().then(() => null, (e: unknown) => e);
    expect(err).toBeInstanceOf(LocalDaemonError);
    expect((err as LocalDaemonError).code).toBe('build');
    expect((err as LocalDaemonError).message).toContain('Codex CLI');
    expect(Object.keys(h.readState().containers)).toHaveLength(0);
  });
});

describe('controller: per-harness state and sign-in', () => {
  async function up(opts: Parameters<typeof makeHarness>[0] = {}) {
    const h = makeHarness({ settings: { enabled: false, port: 7433, harnesses: ['claude', 'codex', 'opencode'] }, secrets: { [CONTAINER_AUTH_TOKEN_SECRET]: CLAUDE }, ...opts });
    await h.controller.setUp();
    return h;
  }
  const setAuth = (h: Awaited<ReturnType<typeof up>>, auth: Record<string, boolean>) => {
    const s = h.readState();
    s.volumes[dataVolumeFor(h.vaultPath)]!.auth = auth;
    h.writeState(s);
  };

  it('the snapshot reports which CLIs are present and which logins exist, from a probe of the running container', async () => {
    const h = await up();
    let snap1 = await h.controller.snapshot();
    expect(snap1.observed.harnessProbe).toEqual({
      claude: { cli: true, signedIn: false }, codex: { cli: true, signedIn: false }, opencode: { cli: true, signedIn: false },
    });
    setAuth(h, { codex: true });
    snap1 = await h.controller.snapshot();
    expect(snap1.observed.harnessProbe?.codex.signedIn).toBe(true);
    expect(snap1.containerName).toBe(h.name);
    const rows = buildHarnessRows(snap1);
    expect(rows.find((r) => r.id === 'codex')!.status).toBe('CLI installed, signed in');
    expect(rows.find((r) => r.id === 'opencode')!.command).toContain(h.name);
  });

  it('a failing probe degrades to "unknown", it does not break the snapshot', async () => {
    const h = await up();
    h.setFail(['exec:probe']);
    const s = await h.controller.snapshot();
    expect(s.observed.harnessProbe).toBeUndefined();
    expect(s.assessment.status).toBe('running');
  });

  it('Codex sign-in runs the device flow in the container and confirms the login landed', async () => {
    const calls: unknown[] = [];
    let hh: Awaited<ReturnType<typeof up>>;
    const h = await up({
      harnessSignIn: async (o) => {
        calls.push(o.containerName);
        o.onUrl('https://auth.openai.com/codex/device');
        o.onProgress('Enter the code ABCD-12345');
        setAuth(hh, { codex: true }); // what the real CLI does inside the container
        return { ok: true };
      },
    });
    hh = h;
    const onUrl = vi.fn();
    await expect(h.controller.signInHarness('codex', { onProgress: vi.fn(), onUrl })).resolves.toEqual({ ok: true });
    expect(calls).toEqual([h.name]);
    expect(onUrl).toHaveBeenCalledWith('https://auth.openai.com/codex/device');
    expect((await h.controller.snapshot()).observed.harnessProbe?.codex.signedIn).toBe(true);
  });

  it('a Codex login that fails, or "succeeds" without leaving a login, says so and includes the exact command', async () => {
    const failing = await up({ harnessSignIn: async () => ({ ok: false, error: 'Codex sign-in did not complete (exit 1).' }) });
    const r1 = await failing.controller.signInHarness('codex', { onProgress: vi.fn(), onUrl: vi.fn() });
    expect(r1.ok).toBe(false);
    expect((r1 as { error: string }).error).toContain('did not complete');
    expect((r1 as { error: string }).error).toContain(`exec -it --user 10001 ${failing.name} /opt/harnesses/bin/codex login --device-auth`);

    const liar = await up({ harnessSignIn: async () => ({ ok: true }) });
    const r2 = await liar.controller.signInHarness('codex', { onProgress: vi.fn(), onUrl: vi.fn() });
    expect(r2.ok).toBe(false);
    expect((r2 as { error: string }).error).toMatch(/no login was found/);
  });

  it('OpenCode cannot be signed in from Settings: it says so with the exact command instead of failing silently', async () => {
    const h = await up();
    const r = await h.controller.signInHarness('opencode', { onProgress: vi.fn(), onUrl: vi.fn() });
    expect(r).toMatchObject({ ok: false });
    expect((r as { error: string }).error).toContain('cannot be signed in from Settings');
    expect((r as { error: string }).error).toContain(`exec -it --user 10001 ${h.name} /opt/harnesses/bin/opencode auth login`);
  });

  it('refuses to sign in a harness that is off or whose CLI is not in the image yet', async () => {
    const off = await up({ settings: { enabled: false, port: 7433, harnesses: ['claude'] }, harnessSignIn: async () => ({ ok: true }) });
    expect(await off.controller.signInHarness('codex', { onProgress: vi.fn(), onUrl: vi.fn() })).toMatchObject({ ok: false, error: expect.stringContaining('turned off') });

    const stale = await up({ harnessSignIn: async () => ({ ok: true }) });
    await stale.controller.setHarnesses(['claude', 'codex', 'opencode']); // image has them
    // image missing codex: simulate by dropping it from the built image record
    const s = stale.readState();
    const ref = localImageRef(stale.pluginVersion, ['claude', 'codex', 'opencode']);
    s.images[ref]!.harnesses = ['claude', 'opencode'];
    stale.writeState(s);
    expect(await stale.controller.signInHarness('codex', { onProgress: vi.fn(), onUrl: vi.fn() })).toMatchObject({ ok: false, error: expect.stringContaining('not in the daemon image') });
  });

  it('keeps every credential out of settings, the keychain and argv: logins live only in the data volume', async () => {
    let hh: Awaited<ReturnType<typeof up>>;
    const h = await up({ harnessSignIn: async () => { setAuth(hh, { codex: true }); return { ok: true }; } });
    hh = h;
    await h.controller.signInHarness('codex', { onProgress: vi.fn(), onUrl: vi.fn() });
    // settings hold the toggle, the port and the daemon-side token ID (not the token): nothing from a login
    expect(Object.keys(h.settings!).sort()).toEqual(['credentialWritten', 'enabled', 'harnesses', 'port', 'tokenId']);
    expect(JSON.stringify(h.settings)).not.toMatch(/sk-|secret-/);
    // only the two secrets that were always there: the Claude sign-in and the daemon's access token
    expect(h.secrets.size).toBe(2);
    expect(h.calls().join('\n')).not.toContain(CLAUDE);
  });
});
