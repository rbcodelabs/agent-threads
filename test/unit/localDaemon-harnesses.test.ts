function fakeChild() {
  const child = Object.assign(new EventEmitter(), {
    stdout: new EventEmitter(), stderr: new EventEmitter(), stdin: { write: vi.fn() }, kill: vi.fn(() => true),
  });
  return child;
}

describe('signInToCodexInContainer', () => {
  const opts = (child: ReturnType<typeof fakeChild>, over: Partial<DeviceLoginOptions> = {}) => ({
    spawn: vi.fn(() => child) as never, hostEnv: {}, containerName: 'n', ...over,
  }) as DeviceLoginOptions;

  it('relays the URL and code, and succeeds when the CLI exits 0', async () => {
    const child = fakeChild();
    const onUrl = vi.fn(); const onProgress = vi.fn();
    const o = opts(child, { onUrl, onProgress });
    const p = signInToCodexInContainer(o);
    child.stdout.emit('data', Buffer.from('Open https://auth.openai.com/codex/device\n'));
    child.stderr.emit('data', 'code: WXYZ-98765\n');
    child.emit('close', 0, null);
    await expect(p).resolves.toEqual({ ok: true });
    expect(onUrl).toHaveBeenCalledWith('https://auth.openai.com/codex/device');
    expect(onProgress.mock.calls.map((c) => c[0]).join('\n')).toContain('WXYZ-98765');
    expect((o.spawn as unknown as ReturnType<typeof vi.fn>).mock.calls[0]![1]).toEqual(codexLoginArgs('n'));
  });

  it('reports a failed login with the CLI\'s own words, redacting anything token-shaped', async () => {
    const child = fakeChild();
    const p = signInToCodexInContainer(opts(child));
    child.stderr.emit('data', 'login failed for sk-abcdefghijklmnop12345\n');
    child.emit('close', 1, null);
    const r = await p;
    expect(r.ok).toBe(false);
    expect((r as { error: string }).error).toContain('exit 1');
    expect((r as { error: string }).error).toContain('<redacted>');
    expect((r as { error: string }).error).not.toContain('sk-abcdefgh');
  });

  it('times out, kills the child and says how to get a new code', async () => {
    vi.useFakeTimers();
    try {
      const child = fakeChild();
      const p = signInToCodexInContainer(opts(child, { timeoutMs: 1000 }));
      await vi.advanceTimersByTimeAsync(1500);
      const r = await p;
      expect(r).toMatchObject({ ok: false });
      expect(child.kill).toHaveBeenCalled();
    } finally { vi.useRealTimers(); }
  });

  it('a spawn that throws is an error result, not a crash', async () => {
    const r = await signInToCodexInContainer({ spawn: (() => { throw new Error('no container'); }) as never, hostEnv: {}, containerName: 'n' });
    expect(r).toEqual({ ok: false, error: expect.stringContaining('no container') });
  });
});

